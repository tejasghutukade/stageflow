import { chromium } from "playwright-core";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1920, height: 1080 }, colorScheme: "dark" });
const p = await ctx.newPage();
await p.goto("http://127.0.0.1:3900/#/runs");
await p.waitForTimeout(1500);
await p.screencast.start({ path: "out/test.webm", size: { width: 1920, height: 1080 }, quality: 100, fps: 30 });
await p.screencast.showActions({ cursor: "pointer", duration: 700 });
await p.getByText("Pipeline runs").first().click();
await p.waitForTimeout(800);
await p.getByText("Agents", { exact: true }).first().click();
await p.waitForTimeout(1500);
await p.getByText("Pipelines", { exact: true }).first().click();
await p.waitForTimeout(1500);
await p.screencast.stop();
await b.close();
