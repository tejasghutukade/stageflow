import { chromium } from "playwright-core";
const base = "http://127.0.0.1:3900";
const rid = (await (await fetch(base + "/api/runs")).json()).runs.find((r) => r.pipeline_id === "vendor-research").run_id;
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1920, height: 1080 }, colorScheme: "dark" })).newPage();
const shot = async (n) => { await p.waitForTimeout(900); await p.screenshot({ path: `out/scout/${n}.png` }); console.log(n); };
await p.goto(`${base}/#/runs`); await p.waitForTimeout(1200);
await p.getByRole("button", { name: /Start a run/ }).first().click(); await shot("startrun");
await p.keyboard.press("Escape");
await p.goto(`${base}/#/runs/${rid}`); await p.waitForTimeout(1200);
await p.getByText("Graph", { exact: true }).click(); await shot("run_graph");
await p.getByText("scope").first().click(); await shot("run_graph_stage");
await p.getByText("Artifacts").first().click(); await shot("run_artifacts");
await p.goto(`${base}/#/inbox`); await shot("inbox2");
await p.goto(`${base}/#/agents/support`); await p.waitForTimeout(800);
await p.getByText("Configuration", { exact: true }).click(); await shot("agent_config");
await p.goto(`${base}/chat/k7x9m2qp4h8d3w6n`); await shot("webchat");
await p.goto(`${base}/#/connections`); await p.waitForTimeout(800);
await p.getByRole("button", { name: "Connect" }).nth(1).click(); await shot("connect_slack");
await b.close();
