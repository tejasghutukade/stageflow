import { chromium } from "playwright-core";
import fs from "node:fs";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 810 }, deviceScaleFactor: 1920 / 1440, colorScheme: "dark" });
const p = await ctx.newPage();
await p.goto("http://127.0.0.1:3900/#/runs"); await p.waitForTimeout(1500);
const cdp = await ctx.newCDPSession(p);
let n = 0;
cdp.on("Page.screencastFrame", async (f) => { n++; fs.writeFileSync("out/cdp-frame.jpg", Buffer.from(f.data, "base64")); console.log(f.metadata.deviceWidth, f.metadata.deviceHeight, f.metadata.timestamp); await cdp.send("Page.screencastFrameAck", { sessionId: f.sessionId }); });
await cdp.send("Page.startScreencast", { format: "jpeg", quality: 100, maxWidth: 1920, maxHeight: 1080, everyNthFrame: 1 });
await p.getByText("Agents", { exact: true }).first().click();
await p.waitForTimeout(1500);
await cdp.send("Page.stopScreencast");
console.log("frames", n);
await b.close();
